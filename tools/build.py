#!/usr/bin/env python3
"""Build ZX-UX UNIX v1: assemble, make the root RAM disk, write the TZX.

  build.py SJASMPLUS_PATH

Outputs (in ../build): unix.bin, fs.img, ZX-UX.tzx, ZX-UX.tap, kernel.json
"""
import hashlib, json, os, re, struct, subprocess, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import zxpack

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, 'src')
OUT = os.path.join(ROOT, 'build')

KBASE = 0x6000
BSIZE = 128
NBLK = 64
NINODE = 64
ROOTINO = 41
DEFTIME = 4495 * 86400                 # Fri 23 Apr 1982, the ZX Spectrum's release (unix.asm)

IALLOC, IFDIR, IFLARGE, IFTEXT, IFPACK = 0x8000, 0x4000, 0x1000, 0x0800, 0x0400
ISUID, IEXEC, IROWN, IWOWN, IROTH, IWOTH = 0x20, 0x10, 0x08, 0x04, 0x02, 0x01

# ---------------------------------------------------------------- programs
# path -> label stem (t_<stem> .. e_<stem> in the assembled image)
PROGRAMS = [
    ('/etc/init', 'init', 0), ('/etc/getty', 'getty', 0),
    ('/etc/glob', 'glob', 0),
    ('/bin/login', 'login', 0), ('/bin/sh', 'sh', 0),
    ('/etc/ldx', 'ldx', 0),
]
EXTRA = os.path.join(SRC, 'programs.txt')   # more programs, one per line
ADDFILES = []

MOTD = ("\n"
        "  Welcome to ZX-UX UNIX v1 for the ZX Spectrum 48K.\n"
        "  Read /usr/doc/zxpack about packed files.\n"
        "\n")

# ---------------------------------------------------------------- assembler
def assemble(sjasm):
    r = subprocess.run([sjasm, '--nologo', '--msg=war', '--sym=unix.sym',
                        'unix.asm'], cwd=SRC,
                       capture_output=True, text=True)
    sys.stdout.write(r.stdout + r.stderr)
    if r.returncode:
        sys.exit('assembly failed')
    syms = {}
    for line in open(os.path.join(SRC, 'unix.sym')):
        m = re.match(r'(\S+): EQU 0x([0-9A-Fa-f]+)', line)
        if m:
            syms[m.group(1)] = int(m.group(2), 16)
    return open(os.path.join(SRC, 'unix.bin'), 'rb').read(), syms


def low_kernel():
    """The low kernel (unix.asm lowk): loaded below the kernel stack."""
    return open(os.path.join(SRC, 'lowk.bin'), 'rb').read()

# ---------------------------------------------------------------- mkfs
# ZX-UX v1: an i-node table (ITAB) and the arena, built as the kernel
# keeps them; the tape loads them right after the resident text.
NINODE = 24
TXINO = 128
INOSZ = 32
K_FREE, K_FILE = 0, 1

def program_list():
    progs = list(PROGRAMS)
    if os.path.exists(EXTRA):
        for line in open(EXTRA):
            line = line.split('#')[0].split()
            if line:
                progs.append((line[0], line[1], int(line[2], 8) if len(line) > 2 else 0))
    return progs

def write_ptab(progs):
    with open(os.path.join(SRC, 'ptab.inc'), 'w') as f:
        f.write('; generated by tools/build.py: text, size, extra mode bits\n')
        for path, stem, extra in progs:
            f.write('        dw t_%s, e_%s-t_%s\n        db %d\n' % (stem, stem, stem, extra))
        f.write('NPROG   equ %d\n' % len(progs))

class FS:
    def __init__(self):
        self.inodes = {}
        self.next_ino = ROOTINO

    def ialloc(self, flags, uid=0):
        i = self.next_ino
        if i >= ROOTINO + NINODE:
            sys.exit('mkfs: out of i-nodes')
        self.next_ino += 1
        self.inodes[i] = dict(flags=flags, nlks=1, uid=uid, data=b'', pack=False, rsvd=0)
        return i

    def image(self, itab, ar0, ar1):
        tab = bytearray(NINODE * INOSZ)
        arena = bytearray()
        for i, n in sorted(self.inodes.items()):
            data = n['data']
            size = len(data)
            if n['pack']:                       # stored packed, as the
                z = zxpack.pack(data)           # kernel's idle packer would
                if len(z) + 8 <= len(data):
                    n['flags'] |= IFPACK
                    n['rsvd'] = len(z)
                    data = z
            ext = 0
            if data:
                ext = ar0 + len(arena) + 4
                bsz = (len(data) + 5) & ~1
                arena += struct.pack('<HBB', bsz, K_FILE, 0) + data
                arena += bytes(bsz - 4 - len(data))
            struct.pack_into('<HBBHH14xIIH', tab, (i - ROOTINO) * INOSZ, n['flags'], n['nlks'],
                             n['uid'], size, ext, DEFTIME, DEFTIME, n['rsvd'])
        free = ar1 - ar0 - len(arena)
        arena += struct.pack('<HBB', free, K_FREE, 0)
        return bytes(tab) + bytes(arena), free

def dirdata(entries):
    out = b''
    for name, ino in entries:
        out += struct.pack('<H', ino) + name.encode().ljust(8, b'\0')[:8]
    return out

def mkfs(syms, progs):
    fs = FS()
    D = IALLOC | IFDIR | IROWN | IWOWN | IROTH
    tree = {}                               # path -> ino
    root = fs.ialloc(D)
    fs.inodes[root]['nlks'] = 2
    tree['/'] = root
    children = {'/': []}

    def mkdir(path, flags=D):
        ino = fs.ialloc(flags)
        tree[path] = ino
        children[path] = []
        parent = os.path.dirname(path)
        children[parent].append((os.path.basename(path), ino))
        fs.inodes[ino]['nlks'] = 2
        fs.inodes[tree[parent]]['nlks'] += 1
        return ino

    for d in ('/bin', '/dev', '/etc', '/tmp', '/usr'):
        mkdir(d, D | IWOTH if d in ('/tmp', '/usr') else D)
    for name, num in (('tty', 1), ('mem', 2), ('tap', 5), ('cassette', 5)):
        children['/dev'].append((name, num))

    def addfile(path, data, flags=IALLOC | IROWN | IWOWN | IROTH, uid=0, pack=False):
        ino = fs.ialloc(flags, uid)
        fs.inodes[ino]['data'] = data
        fs.inodes[ino]['pack'] = pack
        children[os.path.dirname(path)].append((os.path.basename(path), ino))
        return ino

    texts = []
    for k, (path, stem, extra) in enumerate(progs):
        t, e = syms['t_' + stem], syms['e_' + stem]
        children[os.path.dirname(path)].append((os.path.basename(path), TXINO + k))
        texts.append((path, t, e - t))

    addfile('/etc/motd', MOTD.encode(), pack=True)  # as the idle packer would
    mkdir('/usr/doc', D | IWOTH)
    for doc in ('zxpack', 'tar', 'more'):
        addfile('/usr/doc/' + doc, open(os.path.join(SRC, doc + '.doc'), 'rb').read(),
                pack=True)
    for path, local, mode, z in ADDFILES:   # build.py --add path=file:mode[:z]
        addfile(path, open(local, 'rb').read(), IALLOC | mode, pack=z)

    for path, ents in children.items():
        ino = tree[path]
        parent = tree[os.path.dirname(path)] if path != '/' else ino
        fs.inodes[ino]['data'] = dirdata([('.', ino), ('..', parent)] + ents)
    img, free = fs.image(syms['ITAB'], syms['AR0'], syms['WINDOW'])
    return img, texts, free, fs.next_ino - ROOTINO

# ---------------------------------------------------------------- tape
def tap_block(flag, data):
    body = bytes([flag]) + data
    x = 0
    for c in body:
        x ^= c
    return body + bytes([x])

def header(typ, name, length, p1, p2):
    return tap_block(0, bytes([typ]) + name.encode().ljust(10)[:10] +
                     struct.pack('<HHH', length, p1, p2))

def basic_loader():
    def num(n):            # VAL "n" keeps the line short and exact
        return b'\xb0"' + str(n).encode() + b'"'
    line = (b'\xe7' + num(0) + b':' +          # BORDER VAL "0"
            b'\xda' + num(0) + b':' +          # PAPER VAL "0"
            b'\xd9' + num(7) + b':' +          # INK VAL "7"
            b'\xfb:' +                         # CLS
            b'\xfd' + num(KBASE - 1) + b':' +  # CLEAR VAL "24575"
            b'\xf5"ZX-UX UNIX v1 loading":' +   # PRINT "..."
            b'\xef""\xaf:' +                   # LOAD ""CODE  (lowk)
            b'\xef""\xaf:' +                   # LOAD ""CODE  (unix)
            b'\xef""\xaf:' +                   # LOAD ""CODE  (fs)
            b'\xf9\xc0' + num(KBASE) +         # RANDOMIZE USR VAL "24576"
            b'\r')
    return struct.pack('>H', 10) + struct.pack('<H', len(line)) + line

def tzx(blocks, title):
    out = bytearray(b'ZXTape!\x1a\x01\x14')
    # 0x30 text description, 0x32 archive info
    t = title.encode()
    out += bytes([0x30, len(t)]) + t
    info = [(0x00, 'ZX-UX v1'),
            (0x02, 'UNIX v1-inspired system for the 48K ZX Spectrum'),
            (0x03, '2026'), (0x04, 'English'), (0x05, 'Operating system'),
            (0x08, 'ZX-UX v1, 48K ZX Spectrum'),
            (0xFF, 'Log in with any name of up to 8 characters; no passwords.')]
    body = bytes([len(info)])
    for k, s in info:
        s = s.encode()[:255]
        body += bytes([k, len(s)]) + s
    out += bytes([0x32]) + struct.pack('<H', len(body)) + body
    for data, pause in blocks:
        out += bytes([0x10]) + struct.pack('<HH', pause, len(data)) + data
    return bytes(out)

def tap(blocks):
    out = b''
    for data, _ in blocks:
        out += struct.pack('<H', len(data)) + data
    return out

def write_bootinfo(kernel_bytes, free_bytes, process_count):
    """Generate the boot figures from the assembled system and file image."""
    payload = '        db "%dB free=%dB procs=%d ",0\n' % (
        kernel_bytes, free_bytes, process_count)
    path = os.path.join(OUT, 'bootinfo.inc')
    old = open(path).read() if os.path.isfile(path) else None
    if old == payload:
        return False
    with open(path, 'w') as stream:
        stream.write(payload)
    return True


# The kernel addresses sdk/rvm reads (never writes) while it runs the
# real system: which process is running, the pids, the screen owners.
# rvm checks kernel_sha256 and lowk_sha256 against the "unix" and "lowk"
# code blocks on the tape it boots.
RVM_SYMBOLS = ('KV', 'NPROC', 'SFREE', 'SZOMB', 'p_stat', 'p_pid', 'cur', 'scrown')


def write_kernel_json(kern, syms):
    info = {
        'format': 'zx-ux-kernel/1',
        'note': 'Written by tools/build.py from the assembled kernel; read by sdk/rvm.',
        'kernel_sha256': hashlib.sha256(kern).hexdigest(),
        'lowk_sha256': hashlib.sha256(low_kernel()).hexdigest(),
        'kernel_bytes': syms['kend'] - KBASE,
        'syscall': KBASE + 3,
        'symbols': {k: syms[k] for k in RVM_SYMBOLS},
    }
    with open(os.path.join(OUT, 'kernel.json'), 'w', newline='\n') as f:
        json.dump(info, f, indent=1, sort_keys=True)
        f.write('\n')


def main():
    args = sys.argv[1:]
    while args and args[0] == '--add':
        path, _, rest = args[1].partition('=')
        local, _, mode = rest.partition(':')
        mode, _, z = mode.partition(':')
        ADDFILES.append((path, local, int(mode or '36', 8), z == 'z'))
        args = args[2:]
    sjasm = os.path.abspath(args[0]) if args else (os.path.join(HERE, 'bin', 'sjasmplus') if os.path.exists(os.path.join(HERE, 'bin', 'sjasmplus')) else 'sjasmplus')
    os.makedirs(OUT, exist_ok=True)
    progs = program_list()
    write_ptab(progs)
    write_bootinfo(8192, 99999, 4) if not os.path.isfile(
        os.path.join(OUT, 'bootinfo.inc')) else None
    for attempt in range(6):
        kern, syms = assemble(sjasm)
        rd0, texts, nfree, nino = mkfs(syms, progs)
        if not write_bootinfo(syms['kend'] - KBASE, nfree, syms['NPROC']):
            break
    else:
        raise SystemExit('boot figures did not settle after six builds')
    RD0 = syms['ITAB']
    open(os.path.join(OUT, 'unix.bin'), 'wb').write(kern)
    open(os.path.join(OUT, 'lowk.bin'), 'wb').write(low_kernel())
    write_kernel_json(kern, syms)
    open(os.path.join(OUT, 'fs.img'), 'wb').write(rd0)
    bas = basic_loader()
    low = low_kernel()
    blocks = [
        (header(0, 'ZX-UX', len(bas), 10, len(bas)), 1000),
        (tap_block(0xFF, bas), 1000),
        (header(3, 'lowk', len(low), syms['LOWK'], 32768), 1000),
        (tap_block(0xFF, low), 1000),
        (header(3, 'unix', len(kern), KBASE, 32768), 1000),
        (tap_block(0xFF, kern), 1000),
        (header(3, 'fs', len(rd0), RD0, 32768), 1000),
        (tap_block(0xFF, rd0), 2000),
    ]
    open(os.path.join(OUT, 'ZX-UX.tzx'), 'wb').write(
        tzx(blocks, 'ZX-UX v1 - ZX Spectrum 48K'))
    open(os.path.join(OUT, 'ZX-UX.tap'), 'wb').write(tap(blocks))
    print('kernel %d bytes (6000-%04X), user text to %04X, image %d bytes'
          % (syms['kend'] - KBASE, syms['kend'] - 1, syms['utext_end'] - 1, len(kern)))
    print('boot code / zxpack model %04X-%04X, i-nodes %04X-%04X, arena %04X-%04X (%d bytes), '
          'window %04X-%04X, u-area %04X-FFF3'
          % (syms['ZXW'], syms['ITAB'] - 1, syms['ITAB'], syms['AR0'] - 1, syms['AR0'],
             syms['WINDOW'] - 1, syms['WINDOW'] - syms['AR0'], syms['WINDOW'], syms['CORE'] - 1,
             syms['CORE']))
    print('file system: %d i-nodes used of %d, arena %d bytes free, %d programs'
          % (nino, NINODE, nfree, len(texts)))

if __name__ == '__main__':
    main()
